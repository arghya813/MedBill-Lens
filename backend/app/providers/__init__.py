"""Provider registry and fallback composition.

The rest of the application depends only on :class:`AIProvider`. Swapping in
Gemini, a local model, or a bespoke OCR service is a matter of implementing
the interface and registering it here.
"""

from __future__ import annotations

from app.core.config import Settings, settings
from app.core.errors import ProviderError
from app.core.logging import get_logger
from app.providers.base import (
    AIProvider,
    DocumentInput,
    ExplanationContext,
    ExtractedBill,
    ProviderStatus,
    SummaryContext,
)

logger = get_logger(__name__)

#: Returned in place of provider-generated wording when ``AI_FALLBACK_TO_DEMO``
#: is disabled and the configured provider is unreachable. The user still gets
#: every deterministic number; only the prose is withheld.
NO_AI_AVAILABLE = (
    "An automated explanation could not be generated because the configured AI "
    "provider is unavailable and automatic fallback is disabled. All benchmark "
    "figures shown here are still exact."
)


class FallbackProvider(AIProvider):
    """Delegates to a primary provider, optionally falling back to the demo provider.

    The application must remain fully functional when the AI API is
    unavailable, so every language call degrades gracefully. The fallback is
    reported in the response so the UI can label the output honestly.

    When ``allow_fallback`` is ``False`` (``AI_FALLBACK_TO_DEMO=false``) the
    demo provider is *not* substituted: extraction raises so the user can enter
    charges manually, and wording is replaced by :data:`NO_AI_AVAILABLE`.
    """

    def __init__(self, primary: AIProvider | None, fallback: AIProvider, *, allow_fallback: bool = True):
        self.primary = primary
        self.fallback = fallback
        self.allow_fallback = allow_fallback
        self.name = f"{primary.name if primary else 'none'}+fallback"
        # Updated after every delegated call so callers can label output
        # honestly ("generated by the configured AI provider" vs "demo mode").
        self.last_used_real: bool = False
        self.degraded = primary is None

    @property
    def is_real(self) -> bool:  # type: ignore[override]
        """True only when the last operation was served by a real provider."""
        return self.last_used_real

    @property
    def active_name(self) -> str:
        return self.primary.name if self.primary else self.fallback.name

    @property
    def used_real_provider(self) -> bool:
        return self.last_used_real

    async def extract_bill(self, document: DocumentInput) -> ExtractedBill:
        if self.primary is None:
            self.last_used_real = False
            return await self.fallback.extract_bill(document)
        try:
            result = await self.primary.extract_bill(document)
            if not result.is_usable:
                logger.info("provider_extraction_empty result=fallback")
                fallback_result = await self.fallback.extract_bill(document)
                if fallback_result.is_usable:
                    fallback_result.warnings.append(
                        "The AI provider returned no charges, so a rule-based read was used."
                    )
                    self.last_used_real = False
                    return fallback_result
            self.last_used_real = True
            return result
        except ProviderError as exc:
            logger.warning("provider_extract_failed falling_back=%s reason=%s", self.allow_fallback, exc.code)
            self.last_used_real = False
            self.degraded = True
            if not self.allow_fallback:
                # The operator disabled automatic fallback, so do not silently
                # substitute rule-based output. Return an explicit "needs manual
                # entry" result instead of raising a 500 at the user.
                return ExtractedBill(
                    items=[],
                    confidence=0.0,
                    provider=self.name,
                    method="unavailable",
                    warnings=[
                        "The configured AI provider is unavailable and automatic fallback "
                        "is disabled, so the charges could not be read automatically. You "
                        "can enter them manually on the next screen."
                    ],
                )
            result = await self.fallback.extract_bill(document)
            result.warnings.append(
                "The AI provider was unavailable for this document, so a rule-based "
                "extraction was used instead."
            )
            return result

    async def classify_charge(self, description: str, *, category_hint=None, context=None):
        if self.primary is None:
            self.last_used_real = False
            if not self.allow_fallback:
                from app.providers.demo import DemoAIProvider

                return DemoAIProvider().classify_charge(
                    description, category_hint=category_hint, context=context
                )
            return await self.fallback.classify_charge(
                description, category_hint=category_hint, context=context
            )
        try:
            result = await self.primary.classify_charge(
                description, category_hint=category_hint, context=context
            )
            self.last_used_real = result.source == "ai"
            return result
        except ProviderError:
            self.last_used_real = False
            self.degraded = True
            if not self.allow_fallback:
                from app.providers.base import Categorization
                from app.services.categorization import categorize, service_name_for

                rule = categorize(description, category_hint=category_hint)
                return Categorization(
                    category=rule.category,
                    confidence=rule.confidence,
                    service_name=service_name_for(description, rule.category),
                    reason="Deterministic rules (AI provider unavailable, fallback disabled).",
                    source="rules",
                )
            return await self.fallback.classify_charge(
                description, category_hint=category_hint, context=context
            )

    async def explain_difference(self, context: ExplanationContext) -> str:
        if self.primary is None:
            self.last_used_real = False
            if not self.allow_fallback:
                return NO_AI_AVAILABLE
            return await self.fallback.explain_difference(context)
        try:
            result = await self.primary.explain_difference(context)
            self.last_used_real = True
            return result
        except ProviderError:
            self.last_used_real = False
            self.degraded = True
            if not self.allow_fallback:
                return NO_AI_AVAILABLE
            return await self.fallback.explain_difference(context)

    async def generate_questions(self, context: ExplanationContext, *, scope: str = "charge"):
        if self.primary is None:
            self.last_used_real = False
            if not self.allow_fallback:
                return []
            return await self.fallback.generate_questions(context, scope=scope)
        try:
            result = await self.primary.generate_questions(context, scope=scope)
            self.last_used_real = True
            return result
        except ProviderError:
            self.last_used_real = False
            self.degraded = True
            if not self.allow_fallback:
                return []
            return await self.fallback.generate_questions(context, scope=scope)

    async def summarize_bill(self, context: SummaryContext) -> str:
        if self.primary is None:
            self.last_used_real = False
            if not self.allow_fallback:
                return NO_AI_AVAILABLE
            return await self.fallback.summarize_bill(context)
        try:
            result = await self.primary.summarize_bill(context)
            self.last_used_real = True
            return result
        except ProviderError:
            self.last_used_real = False
            self.degraded = True
            if not self.allow_fallback:
                return NO_AI_AVAILABLE
            return await self.fallback.summarize_bill(context)

    async def health(self) -> ProviderStatus:
        if self.primary is None:
            return await self.fallback.health()
        status = await self.primary.health()
        if not status.ready and not self.allow_fallback:
            return ProviderStatus(
                name=self.primary.name,
                is_real=False,
                ready=False,
                detail=(
                    f"Configured AI provider unavailable: {status.detail}. Automatic "
                    f"fallback is disabled, so only deterministic results are available."
                ),
            )
        if not status.ready:
            return ProviderStatus(
                name=self.fallback.name,
                is_real=False,
                ready=True,
                detail=f"Demo provider active. Configured AI provider unavailable: {status.detail}",
            )
        return status

    async def aclose(self) -> None:
        if self.primary is not None:
            await self.primary.aclose()
        await self.fallback.aclose()


_REGISTRY: dict[str, type[AIProvider]] = {}


def register_provider(name: str, factory: type[AIProvider]) -> None:
    _REGISTRY[name] = factory


def available_providers() -> list[str]:
    return sorted(_REGISTRY) + ["demo"]


def _build_primary(config: Settings) -> AIProvider | None:
    from app.providers.openai_compatible import OpenAICompatibleProvider

    name = config.ai_provider
    if name == "demo":
        return None
    if name in _REGISTRY:
        return _REGISTRY[name]()
    if name in {"openai", "openai_compatible", "compatible", "chatgpt", "gpt"}:
        if not config.ai_api_key:
            logger.info("ai_provider_configured_without_key provider=openai action=demo_mode")
            return None
        return OpenAICompatibleProvider(config)
    logger.warning("unknown_ai_provider name=%s action=demo_mode", name)
    return None


def get_provider(config: Settings | None = None) -> FallbackProvider:
    """Build the provider chain for the current configuration."""
    from app.providers.demo import DemoAIProvider

    config = config or settings
    demo = DemoAIProvider()
    primary = _build_primary(config)
    if primary is None:
        return FallbackProvider(None, demo, allow_fallback=config.ai_fallback_to_demo)
    return FallbackProvider(primary, demo, allow_fallback=config.ai_fallback_to_demo)


_provider: AIProvider | None = None


def get_active_provider() -> AIProvider:
    global _provider
    if _provider is None:
        _provider = get_provider()
    return _provider


def reset_provider() -> None:
    """Used by tests and when settings change."""
    global _provider
    _provider = None
