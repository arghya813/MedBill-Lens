AI_NOTICE_DEMO = (
    "Explanations and questions in this report were generated by the deterministic "
    "demo provider. No AI model was used."
)


@dataclass(slots=True)
class _PreviewCharge:
    """A review-screen row shaped like the fields ``analyze_bill`` reads."""

    key: str
    id: str | None
    position: int
    description: str
    service_name: str | None
    category: str
    quantity: float
    total_price: float


@dataclass(slots=True)
class _PreviewBill:
    """Just enough of a bill for the deterministic engine to run against."""

    city: str | None
    hospital_category: str | None
    treatment: str | None
    room_category: str | None
    grand_total: float | None
    items: list[_PreviewCharge]
    country: str | None = None
    currency_code: str | None = None


class AnalysisService:
    def __init__(
        self,
        db: Session,
        *,
        config: Settings | None = None,
        provider: AIProvider | None = None,
    ):
        self.db = db
        self.config = config or settings
        self.provider = provider or get_active_provider()
        self.bill_repo = BillRepository(db)
        self.analysis_repo = AnalysisRepository(db)

    # ------------------------------------------------------------------
    async def run(self, bill_id: str) -> Analysis:
        bill = self._require_confirmed(bill_id)
        self.bill_repo.set_status(bill, BillStatus.ANALYZING.value)
        self.db.flush()

        outcome: EngineOutcome = analyze_bill(self.db, bill, config=self.config)

        analysis = self.analysis_repo.replace_for_bill(
            bill,
            status="completed",
            city=outcome.city,
            hospital_category=outcome.hospital_category,
            treatment=outcome.treatment,
            room_category=outcome.room_category,
            bill_total=outcome.totals.bill_total,
            comparable_subtotal=outcome.totals.comparable_subtotal,
            benchmark_min_total=outcome.totals.benchmark_min_total,
            benchmark_median_total=outcome.totals.benchmark_median_total,
            benchmark_max_total=outcome.totals.benchmark_max_total,
            difference_min=outcome.totals.difference_min,
            difference_max=outcome.totals.difference_max,
            coverage_percent=outcome.totals.coverage_percent,
            items_analyzed=outcome.totals.counts["analyzed"],
            items_within_range=outcome.totals.counts["within_range"],
            items_below_range=outcome.totals.counts["below_range"],
            items_review=outcome.totals.counts["review"],
            items_attention=outcome.totals.counts["attention"],
            items_insufficient_data=outcome.totals.counts["insufficient_data"],
            items_not_comparable=outcome.totals.counts["not_comparable"],
            headline=outcome.headline,
            dataset_label=outcome.dataset_label,
            is_demo_data=outcome.all_demo,
            provider_name=self._provider_name(),
            provider_is_real=bool(getattr(self.provider, "last_used_real", False)),
            thresholds=outcome.thresholds,
            engine_version="1.0.0",
            meta={"notes": outcome.notes},
        )

        rows = []
        for index, result in enumerate(outcome.results):
            row = {
                "bill_item_id": result.bill_item_id,
                "sort_index": index,
                "description": result.description,
                "category": result.category,
                "quantity": result.quantity,
                "actual_amount": result.actual_amount,
                "benchmark_id": result.benchmark_id,
                "matched_service_name": result.matched_service_name,
                "match_score": result.match_score,
                "match_reason": result.match_reason,
                "match_scope": result.match_scope,
                "benchmark_min": result.benchmark_min,
                "benchmark_median": result.benchmark_median,
                "benchmark_max": result.benchmark_max,
                "benchmark_unit_price_median": result.benchmark_unit_price_median,
                "difference_from_median": result.difference_from_median,
                "percentage_difference": result.percentage_difference,
                "percentage_above_max": result.percentage_above_max,
                "percentage_below_min": result.percentage_below_min,
                "flag_status": result.flag.status,
                "flag_label": result.flag.label,
                "flag_reason": result.flag.reason,
                "is_flagged": result.flag.is_flagged,
                "source_name": result.source_name,
                "source_url": result.source_url,
                "source_date": result.source_date,
                "verification_status": result.verification_status,
                "dataset_label": result.dataset_label,
            }
            rows.append(row)

        self.analysis_repo.add_results(analysis, rows)
        self.db.flush()

        # --- language layer (numbers are already fixed at this point) -----
        comparisons = self.analysis_repo.get(analysis.id)
        await self._attach_language(comparisons, bill, outcome)

        analysis = self.analysis_repo.get(analysis.id)
        self.bill_repo.set_status(bill, "completed")
        self.db.flush()
        return analysis

    # ------------------------------------------------------------------
    def preview(self, payload: PreviewRequest) -> PreviewResponse:
        """Compare the review screen's current charges without confirming.

        Deliberately not gated on ``BillNotConfirmedError``: the review screen
        exists so the user can correct what extraction read, and these flags are
        the thing being corrected against. Nothing is written, no AI provider is
        consulted, and the numbers come from the same engine as a full run, so
        the preview and the eventual analysis cannot disagree.
        """
        bill = self.bill_repo.get(payload.bill_id) if payload.bill_id else None
        if payload.bill_id and bill is None:
            from app.core.errors import BillNotFoundError

            raise BillNotFoundError(f"No bill exists with id '{payload.bill_id}'.")

        # The submitted context is authoritative when present: it is exactly
        # what confirming would persist, so a city the user has just changed is
        # reflected before they commit to it.
        context = payload.context
        if context is not None:
            city, hospital_category = context.city, context.hospital_category
            treatment, room_category = context.treatment, context.room_category
            country = context.country
        elif bill is not None:
            city = bill.city
            hospital_category = bill.hospital_category
            treatment = bill.treatment
            room_category = bill.room_category
            country = bill.country
        else:
            city = hospital_category = treatment = room_category = country = None

        charges = [
            _PreviewCharge(
                key=item.key,
                id=item.id,
                position=index,
                description=item.description.strip(),
                service_name=item.service_name,
                category=item.category,
                quantity=item.quantity,
                total_price=item.total_price or 0.0,
            )
            for index, item in enumerate(payload.items)
            if item.description.strip()
        ]

        outcome = analyze_bill(
            self.db,
            _PreviewBill(
                city=city,
                hospital_category=hospital_category,
                treatment=treatment,
                room_category=room_category,
                grand_total=bill.grand_total if bill is not None else None,
                items=charges,
                country=country,
                currency_code=bill.currency_code if bill is not None else None,
            ),
            config=self.config,
        )

        comparisons = [
            self._comparison_row(
                result,
                row_id=charge.key,
                bill_item_id=charge.id,
                sort_index=charge.position,
                flag_status=result.flag.status,
                flag_label=result.flag.label,
                flag_reason=result.flag.reason,
                is_flagged=result.flag.is_flagged,
                dataset_fallback=outcome.dataset_label,
                symbol=symbol_for_currency(
                    (bill.currency_code if bill is not None else None)
                    or self.config.currency_code
                ),
            )
            for charge, result in zip(charges, outcome.results, strict=True)
        ]

        notices = list(outcome.notes)
        if outcome.all_demo:
            notices.insert(0, DatasetLabel.DEMO.value)
        notices.append(TOOL_NOTICE)

        return PreviewResponse(
            bill_id=payload.bill_id,
            comparisons=comparisons,
            counts=AnalysisCounts(**outcome.totals.counts),
            coverage_percent=outcome.totals.coverage_percent,
            headline=outcome.headline,
            dataset_label=outcome.dataset_label,
            is_demo_data=outcome.all_demo,
            notices=notices,
            disclaimer=SAFE_DISCLAIMER,
            context=AnalysisContextOut(
                city=city,
                hospital_category=hospital_category,
                treatment=treatment,
                room_category=room_category,
                country=country,
            ),
        )

    # ------------------------------------------------------------------
    async def _attach_language(self, analysis, bill: Bill, outcome: EngineOutcome) -> None:
        flagged = [r for r in analysis.results if r.is_flagged]
        attention_first = sorted(
            flagged,
            key=lambda r: -(r.percentage_above_max or 0.0),
        )
        for row in attention_first:
            ctx = self._context_for(bill, outcome, row)
            try:
                explanation = await self.provider.explain_difference(ctx)
                questions = await self.provider.generate_questions(ctx, scope="charge")
            except Exception:  # pragma: no cover - provider falls back internally
                logger.warning("language_layer_failed analysis=%s", analysis.id)
                continue
            row.ai_explanation = explanation
            row.ai_questions = questions
            row.ai_explanation_source = self._provider_name()
            self.db.flush()

        # A neutral, deterministic explanation is still produced for
        # insufficient-data rows so the user always sees an explanation.
        for row in analysis.results:
            if row.is_flagged or row.flag_status == FlagStatus.INSUFFICIENT_DATA.value:
                if not row.ai_explanation:
                    ctx = self._context_for(bill, outcome, row)
                    try:
                        row.ai_explanation = await self.provider.explain_difference(ctx)
                        row.ai_explanation_source = self._provider_name()
                    except Exception:  # pragma: no cover
                        continue
        self.db.flush()

        summary_ctx = self._summary_context(bill, analysis, outcome)
        try:
            analysis.summary = await self.provider.summarize_bill(summary_ctx)
        except Exception:  # pragma: no cover
            analysis.summary = None
        analysis.provider_name = self._provider_name()
        analysis.provider_is_real = bool(getattr(self.provider, "last_used_real", False))
        self.db.flush()

    def _context_for(self, bill: Bill, outcome: EngineOutcome, row) -> ExplanationContext:
        return ExplanationContext(
            description=row.description,
            category=row.category,
            category_label=CATEGORY_LABELS.get(row.category, "Charge"),
            quantity=row.quantity,
            actual_amount=row.actual_amount,
            benchmark_min=row.benchmark_min,
            benchmark_median=row.benchmark_median,
            benchmark_max=row.benchmark_max,
            percentage_above_max=row.percentage_above_max,
            percentage_difference=row.percentage_difference,
            flag_status=row.flag_status,
            flag_label=row.flag_label,
            matched_service_name=row.matched_service_name,
            city=outcome.city,
            hospital_category=outcome.hospital_category,
            treatment=outcome.treatment,
            room_category=outcome.room_category,
            source_name=row.source_name,
            dataset_label=row.dataset_label or outcome.dataset_label,
        )

    def _summary_context(self, bill: Bill, analysis, outcome: EngineOutcome) -> SummaryContext:
        top = sorted(
            [r for r in analysis.results if r.is_flagged],
            key=lambda r: -abs(r.difference_from_median or 0.0),
        )[:5]
        return SummaryContext(
            hospital_name=bill.hospital_name,
            bill_total=analysis.bill_total,
            benchmark_min_total=analysis.benchmark_min_total,
            benchmark_max_total=analysis.benchmark_max_total,
            difference_min=analysis.difference_min,
            difference_max=analysis.difference_max,
            items_analyzed=analysis.items_analyzed,
            items_within_range=analysis.items_within_range + analysis.items_below_range,
            items_above_range=analysis.items_attention + analysis.items_review,
            items_insufficient_data=analysis.items_insufficient_data,
            coverage_percent=analysis.coverage_percent,
            top_flagged=[
                (r.description, r.flag_label, r.percentage_above_max) for r in top
            ],
            city=outcome.city,
            hospital_category=outcome.hospital_category,
            treatment=outcome.treatment,
            dataset_label=analysis.dataset_label,
        )

    # ------------------------------------------------------------------
    async def bill_questions(self, bill_id: str) -> list[str]:
        bill = self._require_confirmed(bill_id)
        analysis = self.analysis_repo.get_for_bill(bill_id)
        if analysis is None:
            outcome = analyze_bill(self.db, bill, config=self.config)
            ctx = ExplanationContext(
                description=bill.hospital_name or "the whole bill",
                category=ChargeCategory.MISCELLANEOUS.value,
                category_label="Bill",
                quantity=1,
                actual_amount=round_money(bill.grand_total or 0.0),
                benchmark_min=None,
                benchmark_median=None,
                benchmark_max=None,
                percentage_above_max=None,
                percentage_difference=None,
                flag_status=FlagStatus.INSUFFICIENT_DATA.value,
                flag_label="Whole bill",
                matched_service_name=None,
                city=outcome.city,
                hospital_category=outcome.hospital_category,
                treatment=outcome.treatment,
                room_category=outcome.room_category,
                source_name=None,
                dataset_label=outcome.dataset_label,
            )
            return await self.provider.generate_questions(ctx, scope="bill")

        row = analysis.results[0] if analysis.results else None
        if row is not None:
            outcome_city, outcome_hospital = analysis.city, analysis.hospital_category
            outcome_treatment, outcome_room = analysis.treatment, analysis.room_category
        else:
            outcome_city = outcome_hospital = outcome_treatment = outcome_room = None

        ctx = ExplanationContext(
            description=row.description if row is not None else "the whole bill",
            category=row.category if row is not None else ChargeCategory.MISCELLANEOUS.value,
            category_label=CATEGORY_LABELS.get(
                row.category if row is not None else "miscellaneous", "Bill"
            ),
            quantity=row.quantity if row is not None else 1,
            actual_amount=round_money(analysis.bill_total),
            benchmark_min=None,
            benchmark_median=None,
            benchmark_max=None,
            percentage_above_max=None,
            percentage_difference=None,
            flag_status=FlagStatus.INSUFFICIENT_DATA.value,
            flag_label="Whole bill",
            matched_service_name=None,
            city=outcome_city,
            hospital_category=outcome_hospital,
            treatment=outcome_treatment,
            room_category=outcome_room,
            source_name=None,
            dataset_label=analysis.dataset_label,
        )
        questions = await self.provider.generate_questions(ctx, scope="bill")
        existing = [q for r in analysis.results for q in (r.ai_questions or [])]
        merged = list(dict.fromkeys([*existing, *questions]))
        return merged[:12]

    # ------------------------------------------------------------------
    def _require_confirmed(self, bill_id: str) -> Bill:
        bill = self.bill_repo.get(bill_id)
        if bill is None:
            from app.core.errors import BillNotFoundError

            raise BillNotFoundError(f"No bill exists with id '{bill_id}'.")
        if bill.status not in {"confirmed", "analyzing", "completed"}:
            # Distinct from "no analysis yet" so the UI can send the user back
            # to the review screen rather than to a retry button.
            raise BillNotConfirmedError(
                f"The bill is currently '{bill.status}'; it must be confirmed first."
            )
        return bill

    def _provider_name(self) -> str:
        return getattr(self.provider, "active_name", None) or self.provider.name

    # ------------------------------------------------------------------
    def to_schema(self, analysis: Analysis, *, questions: list[str] | None = None) -> AnalysisOut:
        bill = self.bill_repo.get(analysis.bill_id)
        symbol = symbol_for_currency(
            (bill.currency_code if bill is not None else None)
            or self.config.currency_code
        )
        comparisons = [
            self._comparison_schema(r, symbol=symbol) for r in analysis.results
        ]
        flagged = [c for c in comparisons if c.is_flagged]
        flagged.sort(key=lambda c: -abs(c.difference_from_median or 0.0))

        totals = AnalysisTotals(
            bill_total=round_money(analysis.bill_total),
            comparable_subtotal=round_money(analysis.comparable_subtotal),
            benchmark_min_total=analysis.benchmark_min_total,
            benchmark_median_total=analysis.benchmark_median_total,
            benchmark_max_total=analysis.benchmark_max_total,
            difference_min=analysis.difference_min,
            difference_max=analysis.difference_max,
            difference_display=format_difference(
                analysis.difference_min, analysis.difference_max, symbol
            ),
            benchmark_display=format_range(
                analysis.benchmark_min_total, analysis.benchmark_max_total, symbol
            ),
            coverage_percent=_coverage(analysis),
        )

        counts = AnalysisCounts(
            analyzed=analysis.items_analyzed,
            within_range=analysis.items_within_range,
            below_range=analysis.items_below_range,
            above_range=analysis.items_attention + analysis.items_review,
            review=analysis.items_review,
            attention=analysis.items_attention,
            insufficient_data=analysis.items_insufficient_data,
            not_comparable=analysis.items_not_comparable,
        )

        notices = list((analysis.meta or {}).get("notes", []))
        if analysis.is_demo_data:
            notices.insert(0, DatasetLabel.DEMO.value)
        notices.append(TOOL_NOTICE)

        return AnalysisOut(
            id=analysis.id,
            bill_id=analysis.bill_id,
            status=analysis.status,
            created_at=analysis.created_at,
            context=AnalysisContextOut(
                city=analysis.city,
                hospital_category=analysis.hospital_category,
                treatment=analysis.treatment,
                room_category=analysis.room_category,
                country=bill.country if bill is not None else None,
            ),
            totals=totals,
            counts=counts,
            comparisons=comparisons,
            flagged=flagged,
            chart_data=self._charts(analysis, symbol),
            questions=questions or [],
            summary=analysis.summary,
            headline=analysis.headline,
            dataset_label=analysis.dataset_label,
            is_demo_data=analysis.is_demo_data,
            provider_name=analysis.provider_name,
            provider_is_real=analysis.provider_is_real,
            thresholds=analysis.thresholds or thresholds_snapshot(self.config),
            engine_version=analysis.engine_version,
            disclaimer=SAFE_DISCLAIMER,
            notices=notices,
        )

    def _comparison_schema(self, row, *, symbol: str | None = None) -> ChargeComparisonOut:
        return self._comparison_row(
            row,
            row_id=row.id,
            bill_item_id=row.bill_item_id,
            sort_index=row.sort_index,
            # Stored results flatten the flag onto the row; the engine nests it.
            flag_status=row.flag_status,
            flag_label=row.flag_label,
            flag_reason=row.flag_reason,
            is_flagged=row.is_flagged,
            ai_explanation=row.ai_explanation,
            ai_questions=list(row.ai_questions or []),
            ai_explanation_source=row.ai_explanation_source,
            symbol=symbol,
        )

    def _comparison_row(
        self,
        result,
        *,
        row_id: str,
        bill_item_id: str | None,
        sort_index: int,
        flag_status: str,
        flag_label: str,
        flag_reason: str,
        is_flagged: bool,
        dataset_fallback: str | None = None,
        ai_explanation: str | None = None,
        ai_questions: list[str] | None = None,
        ai_explanation_source: str | None = None,
        symbol: str | None = None,
    ) -> ChargeComparisonOut:
        """Shape a comparison result for the API.

        Shared by stored analyses and the unsaved review-screen preview so the
        two render identically in the client.
        """
        symbol = symbol or symbol_for_currency(self.config.currency_code)
        has_benchmark = result.benchmark_min is not None and result.benchmark_max is not None
        if has_benchmark:
            benchmark_display = format_range(result.benchmark_min, result.benchmark_max, symbol)
        else:
            benchmark_display = "No sufficient benchmark data"
        difference_display = (
            format_money(result.difference_from_median, symbol)
            if result.difference_from_median is not None
            else "—"
        )
        return ChargeComparisonOut(
            id=row_id,
            bill_item_id=bill_item_id,
            sort_index=sort_index,
            description=result.description,
            category=result.category,
            quantity=result.quantity,
            actual_amount=result.actual_amount,
            matched_service_name=result.matched_service_name,
            match_score=result.match_score,
            match_reason=result.match_reason,
            match_scope=result.match_scope,
            benchmark_min=result.benchmark_min,
            benchmark_median=result.benchmark_median,
            benchmark_max=result.benchmark_max,
            benchmark_unit_price_median=result.benchmark_unit_price_median,
            benchmark_display=benchmark_display,
            benchmark_available=has_benchmark,
            difference_from_median=result.difference_from_median,
            percentage_difference=result.percentage_difference,
            percentage_above_max=result.percentage_above_max,
            percentage_below_min=result.percentage_below_min,
            difference_display=difference_display,
            flag_status=flag_status,
            flag_label=flag_label,
            flag_reason=flag_reason,
            is_flagged=is_flagged,
            source_name=result.source_name,
            source_url=result.source_url,
            source_date=result.source_date,
            verification_status=result.verification_status,
            dataset_label=result.dataset_label or dataset_fallback,
            ai_explanation=ai_explanation,
            ai_questions=ai_questions or [],
            ai_explanation_source=ai_explanation_source,
        )

    def _charts(self, analysis: Analysis, symbol: str) -> ChartData:
        by_category: dict[str, dict] = {}
        for row in analysis.results:
            entry = by_category.setdefault(
                row.category,
                {
                    "actual": 0.0,
                    "benchmark_min": 0.0,
                    "benchmark_max": 0.0,
                    "has_benchmark": False,
                },
            )
            entry["actual"] = round_money(entry["actual"] + row.actual_amount)
            if row.benchmark_min is not None and row.benchmark_max is not None:
                entry["benchmark_min"] = round_money(entry["benchmark_min"] + row.benchmark_min)
                entry["benchmark_max"] = round_money(entry["benchmark_max"] + row.benchmark_max)
                entry["has_benchmark"] = True

        total_actual = sum(e["actual"] for e in by_category.values()) or 1.0
        category_spend: list[CategorySpend] = []
        for category, entry in sorted(by_category.items(), key=lambda kv: -kv[1]["actual"]):
            diff = (
                round_money(entry["actual"] - entry["benchmark_max"])
                if entry["has_benchmark"]
                else None
            )
            category_spend.append(
                CategorySpend(
                    category=category,
                    label=CATEGORY_LABELS.get(category, category.replace("_", " ").title()),
                    actual=entry["actual"],
                    benchmark_min=entry["benchmark_min"] if entry["has_benchmark"] else None,
                    benchmark_max=entry["benchmark_max"] if entry["has_benchmark"] else None,
                    difference=diff,
                    percent_of_bill=round(entry["actual"] / total_actual * 100, 1),
                    has_benchmark=entry["has_benchmark"],
                )
            )

        actual_vs_benchmark = []
        for row in analysis.results:
            if row.benchmark_max is None:
                continue
            actual_vs_benchmark.append(
                {
                    "charge": _short(row.description, 28),
                    "category": CATEGORY_LABELS.get(row.category, row.category),
                    "actual": round_money(row.actual_amount),
                    "benchmark_min": row.benchmark_min,
                    "benchmark_median": row.benchmark_median,
                    "benchmark_max": row.benchmark_max,
                    "status": row.flag_status,
                }
            )
        actual_vs_benchmark.sort(key=lambda d: -d["actual"])

        return ChartData(category_spend=category_spend, actual_vs_benchmark=actual_vs_benchmark)


def _coverage(analysis: Analysis) -> float:
    if not analysis.items_analyzed:
        return 0.0
    covered = analysis.items_within_range + analysis.items_below_range + analysis.items_review + analysis.items_attention
    return round(covered / analysis.items_analyzed * 100, 1)


def _short(text: str, limit: int) -> str:
    text = text.strip()
    return text if len(text) <= limit else text[: limit - 1] + "…"
