"""Analysis orchestration.

Splits the work cleanly:

1. ``benchmark_engine`` produces every number, deterministically.
2. The AI provider is then given those numbers as read-only context and asked
   only for language: an explanation per flagged charge, questions, and a
   plain-English summary.

If the provider is unavailable the numeric results are still complete; only the
prose degrades, and the response says so.
"""

